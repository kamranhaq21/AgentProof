# --- criterion 4: jsonschema is dev-only (AD-16) --------------------------------------------

_IMPORT_PROBE = """
import importlib, importlib.util, json, sys
names = json.loads(sys.argv[1])
for name in names:
    importlib.import_module(name)
available = {
    "jsonschema": importlib.util.find_spec("jsonschema") is not None,
    "referencing": importlib.util.find_spec("referencing") is not None,
}
loaded = sorted(
    module
    for module in sys.modules
    if module.split(".")[0] in {"jsonschema", "referencing", "agentproof"}
)
print(json.dumps({"available": available, "loaded": loaded}))
"""


def _models_modules() -> list[str]:
    found = [
        f"agentproof.models.{info.name}"
        for info in pkgutil.iter_modules(agentproof.models.__path__)
    ]
    assert "agentproof.models.export_schemas" in found
    return ["agentproof", "agentproof.models", *found]


def test_importing_agentproof_and_every_models_module_never_imports_jsonschema() -> None:
    names = _models_modules()
    completed = subprocess.run(
        [sys.executable, "-I", "-c", _IMPORT_PROBE, json.dumps(names)],
        capture_output=True,
        text=True,
        encoding="utf-8",
        timeout=SUBPROCESS_TIMEOUT_SECONDS,
        check=False,
    )
    assert completed.returncode == 0, completed.stderr
    probe = json.loads(completed.stdout)
    assert probe["available"] == {"jsonschema": True, "referencing": True}, (
        "the dev environment must have both installed for this test to prove anything"
    )
    assert set(names) <= set(probe["loaded"])
    forbidden = [m for m in probe["loaded"] if m.split(".")[0] in {"jsonschema", "referencing"}]
    assert forbidden == []


def test_jsonschema_and_referencing_are_dev_dependencies_only() -> None:
    with (PACKAGE_ROOT / "pyproject.toml").open("rb") as handle:
        pyproject = tomllib.load(handle)
    runtime = [dep.split(">=")[0] for dep in pyproject["project"]["dependencies"]]
    dev = [dep.split(">=")[0] for dep in pyproject["dependency-groups"]["dev"]]
    assert "jsonschema" not in runtime and "referencing" not in runtime
    assert "jsonschema" in dev and "referencing" in dev
